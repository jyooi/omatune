export function firewireIdFromSerial(serial: string): Uint8Array {
  const hex = serial.trim().toLowerCase().replace(/^0x/u, "");
  if (!/^[0-9a-f]{16}$/u.test(hex)) {
    throw new ItunesdbSignatureError("FireWire ID must be 16 hex digits");
  }
  const out = new Uint8Array(FIREWIRE_BYTES);
  for (let i = 0; i < FIREWIRE_BYTES; i += 1) {
    out[i] = Number.parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}

export function signHash58(bytes: Uint8Array, firewireId: Uint8Array): Uint8Array {
  if (firewireId.byteLength < FIREWIRE_BYTES) {
    throw new ItunesdbSignatureError("FireWire ID must be 8 bytes");
  }
  const need = HASH58_OFFSET + HASH58_LENGTH;
  if (bytes.byteLength < need) {
    throw new ItunesdbSignatureError(`iTunesDB is shorter than ${need} bytes`);
  }
  const out = bytes.slice();
  const dbId = out.slice(DB_ID_OFFSET, DB_ID_OFFSET + DB_ID_LENGTH);
  const unk32 = out.slice(UNK32_OFFSET, UNK32_OFFSET + UNK32_LENGTH);
  out.fill(0, DB_ID_OFFSET, DB_ID_OFFSET + DB_ID_LENGTH);
  out.fill(0, UNK32_OFFSET, UNK32_OFFSET + UNK32_LENGTH);
  out.fill(0, HASH58_OFFSET, HASH58_OFFSET + HASH58_LENGTH);
  writeU16(out, HASHING_SCHEME_OFFSET, HASH58_SCHEME);
  const digest = hmacSha1(deriveKey(firewireId), out);
  out.set(digest, HASH58_OFFSET);
  out.set(dbId, DB_ID_OFFSET);
  out.set(unk32, UNK32_OFFSET);
  return out;
}

function deriveKey(firewireId: Uint8Array): Uint8Array {
  const mixed = new Uint8Array(16);
  for (let i = 0; i < 4; i += 1) {
    const a = requiredByte(firewireId, i * 2);
    const b = requiredByte(firewireId, i * 2 + 1);
    const pairLcm = lcm(a, b);
    const hi = (pairLcm >> 8) & 0xff;
    const lo = pairLcm & 0xff;
    mixed[i * 4] = sbox(AES_SBOX, hi);
    mixed[i * 4 + 1] = sbox(AES_INV_SBOX, hi);
    mixed[i * 4 + 2] = sbox(AES_SBOX, lo);
    mixed[i * 4 + 3] = sbox(AES_INV_SBOX, lo);
  }
  const digest = createHash("sha1").update(FIRMWARE_SEED).update(mixed).digest();
  const key = new Uint8Array(HMAC_KEY_LENGTH);
  key.set(digest, 0);
  return key;
}

function hmacSha1(key: Uint8Array, message: Uint8Array): Uint8Array {
  return new Uint8Array(createHmac("sha1", key).update(message).digest());
}

function lcm(a: number, b: number): number {
  if (a === 0 || b === 0) {
    return 1;
  }
  return (a * b) / gcd(a, b);
}

function gcd(left: number, right: number): number {
  let a = left;
  let b = right;
  while (b !== 0) {
    const remainder = a % b;
    a = b;
    b = remainder;
  }
  return a;
}

function sbox(table: Uint8Array, index: number): number {
  const value = table[index];
  if (value === undefined) {
    throw new ItunesdbSignatureError(`s-box index ${index} is out of range`);
  }
  return value;
}

function requiredByte(bytes: Uint8Array, index: number): number {
  const value = bytes[index];
  if (value === undefined) {
    throw new ItunesdbSignatureError(`need FireWire ID byte at ${index}`);
  }
  return value;
}
